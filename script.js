let answered = false;
let finalPercentage = 0;
let selectedExam = exams.web;
let questions = selectedExam.questions;
let userAnswers = Array(questions.length).fill(null);

function renderQuestion() {
  const item = questions[current];
  const savedAnswer = userAnswers[current];
  answered = savedAnswer !== null;
  feedback.textContent = "";
  feedback.className = "feedback";
  nextBtn.disabled = !answered;
  prevBtn.disabled = current === 0;
  nextBtn.textContent = current === questions.length - 1 ? "عرض النتيجة" : "التالي";

  questionText.textContent = item.text;
  questionType.textContent = item.type;
  answersBox.className = "answers";
  questionCount.textContent = `السؤال ${current + 1} من ${questions.length}`;
  updateScoreDisplay();
  updateProgress();
  answeredCount.textContent = answeredTotal();
  correctCount.textContent = score;

  answersBox.innerHTML = "";
  item.answers.forEach((answer) => {
    const button = document.createElement("button");
    button.className = "answer";
    button.type = "button";
    button.textContent = answer;
    button.addEventListener("click", () => lockQuestion(answer));
    answersBox.appendChild(button);
  });

  if (answered) {
    showSavedAnswer(savedAnswer);
  }
}

function switchQuestion(nextStep) {
  questionCard.classList.add("switching");

  window.setTimeout(() => {
    nextStep();
    window.requestAnimationFrame(() => {
      questionCard.classList.remove("switching");
    });
  }, 180);
}

function lockQuestion(selectedAnswer) {
  if (answered) return;

  const item = questions[current];
  const buttons = [...document.querySelectorAll(".answer")];
  const isCorrect = selectedAnswer === item.correct;
  answered = true;
  userAnswers[current] = selectedAnswer;

  if (isCorrect) {
    score += 1;
    feedback.textContent = "إجابة صحيحة، ممتاز!";
    feedback.classList.add("good");
  } else {
    feedback.textContent = `إجابة غير صحيحة. الإجابة الصحيحة: ${item.correct}`;
    feedback.classList.add("bad");
  }

  buttons.forEach((button) => {
    button.disabled = true;
    if (button.textContent === item.correct) {
      button.classList.add("correct");
    } else if (button.textContent === selectedAnswer) {
      button.classList.add("wrong");
    }
  });

  updateScoreDisplay();
  answeredCount.textContent = answeredTotal();
  correctCount.textContent = score;
  updateProgress();
  nextBtn.disabled = false;
}

function showSavedAnswer(savedAnswer) {
  const item = questions[current];
  const buttons = [...document.querySelectorAll(".answer")];
  const isCorrect = savedAnswer === item.correct;

  feedback.textContent = isCorrect ? "إجابة صحيحة، ممتاز!" : `إجابة غير صحيحة. الإجابة الصحيحة: ${item.correct}`;
  feedback.classList.add(isCorrect ? "good" : "bad");

  buttons.forEach((button) => {
    button.disabled = true;
    if (button.textContent === item.correct) {
      button.classList.add("correct");
    } else if (button.textContent === savedAnswer) {
      button.classList.add("wrong");
    }
  });
}

function showResult() {
  const percentage = Math.round((score / questions.length) * 100);
  finalPercentage = percentage;
  const finalMessage = getFinalMessage(percentage);
  questionType.textContent = "النتيجة";
  questionText.textContent = "درجتك النهائية";
  answersBox.className = "answers result-view";
  answersBox.innerHTML = `
    <strong>${percentage}%</strong>
    <span>${score} من ${questions.length} إجابات صحيحة</span>
  `;
  feedback.textContent = finalMessage;
  feedback.className = percentage >= 60 ? "feedback good" : "feedback bad";
  prevBtn.disabled = true;
  nextBtn.disabled = true;
  nextBtn.textContent = "انتهى";
  questionCount.textContent = "اكتمل الاختبار";
  progressBar.style.width = "100%";
  answeredCount.textContent = questions.length;
  correctCount.textContent = score;
  updateScoreDisplay();
  updateCertificatePanel(percentage);
}

function answeredTotal() {
  return userAnswers.filter((answer) => answer !== null).length;
}

function updateProgress() {
  const percentage = Math.round((answeredTotal() / questions.length) * 100);
  progressBar.style.width = `${percentage}%`;
}

function updateScoreDisplay() {
  const percentage = questions.length ? Math.round((score / questions.length) * 100) : 0;
  scoreLabel.textContent = `${score} نقطة`;
  progressPercent.textContent = `${percentage}%`;
}

function getFinalMessage(percentage) {
  if (percentage >= 90) {
    return "اشطر كتكوت، نتيجة ممتازة جدًا!";
  }

  if (percentage >= 70) {
    return "نتيجة قوية. واضح إنك مركز وكمل بنفس المستوى.";
  }

  if (percentage >= 50) {
    return "محاولة كويسة. راجع الأخطاء وجرب تاني وهتشوف فرق واضح.";
  }

  return "ولا يهمك. كل محاولة بتقربك أكتر، خد نفس وابدأ من جديد.";
}

function updateCertificatePanel(percentage) {
  if (percentage < 90) {
    certificatePanel.classList.add("hidden");
    return;
  }

  certificatePanel.classList.remove("hidden");
}

function startExam(examKey) {
  selectedExam = exams[examKey] || exams.web;
  questions = selectedExam.questions;
  userAnswers = Array(questions.length).fill(null);
  current = 0;
  score = 0;
  finalPercentage = 0;
  document.getElementById("quiz-title").textContent = selectedExam.title;
  certificatePanel.classList.add("hidden");
  studentName.value = "";
  startPanel.classList.add("hidden");
  quizPanel.classList.remove("hidden");
  sidePanel.classList.remove("hidden");
  renderQuestion();
}

async function downloadCertificate() {
  if (!window.jspdf) {
    alert("تحميل الشهادة يحتاج اتصال بالإنترنت لتحميل مكتبة PDF.");
    return;
  }

  const name = studentName.value.trim() || "الطالب المميز";

  downloadCertificateBtn.disabled = true;
  downloadCertificateBtn.textContent = "جاري التحميل...";

  try {
    await document.fonts.ready;
    const template = await loadImage(certificateTemplateSrc);
    const canvas = document.createElement("canvas");
    canvas.width = template.naturalWidth;
    canvas.height = template.naturalHeight;

    const ctx = canvas.getContext("2d");
    ctx.drawImage(template, 0, 0, canvas.width, canvas.height);
    drawStudentName(ctx, name);

    const image = canvas.toDataURL("image/png");
    const { jsPDF } = window.jspdf;
    const pdf = new jsPDF("landscape", "mm", "a4");
    pdf.addImage(image, "PNG", 0, 0, 297, 210);
    pdf.save(`certificate-${name}.pdf`);
  } catch (error) {
    alert(error.message || "تعذر تحميل الشهادة. تأكد إن ملف صورة الشهادة موجود بجانب ملفات الموقع.");
  } finally {
    downloadCertificateBtn.disabled = false;
    downloadCertificateBtn.textContent = "تحميل الشهادة PDF";
  }
}

function loadImage(src) {
  return new Promise((resolve, reject) => {
    const image = new Image();
    image.onload = () => resolve(image);
    image.onerror = () => reject(new Error("تعذر تحميل صورة الشهادة."));
    image.src = encodeURI(src);
  });
}

function drawStudentName(ctx, name) {
  const centerX = 1988;
  const baselineY = 872;
  const maxWidth = 720;

  ctx.save();
  ctx.direction = "rtl";
  ctx.textAlign = "center";
  ctx.textBaseline = "alphabetic";
  ctx.fillStyle = "#2f5689";
  ctx.font = `900 ${fitNameFontSize(ctx, name, maxWidth)}px Cairo, Tahoma, Arial, sans-serif`;
  ctx.fillText(name, centerX, baselineY, maxWidth);
  ctx.restore();
}

function fitNameFontSize(ctx, name, maxWidth) {
  let size = 86;
  while (size > 44) {
    ctx.font = `900 ${size}px Cairo, Tahoma, Arial, sans-serif`;
    if (ctx.measureText(name).width <= maxWidth) {
      return size;
    }
    size -= 4;
  }
  return size;
}

